"""The owner's cross-check review list, `data/review/<source_id>/crosscheck.md` (M1.2).

Generated by `make ingest` and committed: its diff shows when a source or override change moves
a finding. Sections follow the owner's review order: meaning-changing overrides and priority
units, the other overrides, the snapshot units, then the flagged units, worst coverage first.

Every snapshot and flagged unit carries one review line, which the owner edits in place:

    Review: reviewed_by: faqih | verdict: komdigi_ok

Regeneration reads the lines back from the committed file and keeps them, so a partial review
survives `make ingest` and the snapshot test (committed file == regenerated file) stays green.
A review line on a unit that is no longer listed is dropped, which shows in the diff.
"""

import re
from collections import Counter
from dataclasses import dataclass

from pdp_ingest.crosscheck import THRESHOLD, Finding
from pdp_ingest.overrides import Override, counts
from pdp_ingest.pipeline import TextResult
from pdp_ingest.registry import SourceEntry

VERDICTS = ("komdigi_ok", "override_needed", "ocr_noise")
PENDING = "-"
PENDING_LINE = f"Review: reviewed_by: {PENDING} | verdict: {PENDING}"
_REVIEW = re.compile(r"Review: reviewed_by: (\S+) \| verdict: (\S+)")
_SECTION = re.compile(r"## (\d+)\. ")
_HEADING = re.compile(r"### `([^`]+)`")
SNAPSHOT_SECTION, FLAGGED_SECTION = "3", "4"

# Units the owner checks against the PDF page images as the snapshot sample (roadmap M1.2 DoD);
# their exact text is pinned in tests/test_segment_uu27.py.
SNAPSHOT_UNITS = {
    "uu27-2022": (
        "p1/n1",
        "p53/a1/hb",
        "p5",
        "p20/a2/hc",
        "p26/a2",
        "p46/a3",
        "p57/a3",
        "p67/a1",
        "p76",
        "p57/a3#pj",
    ),
}
# Units reviewed first with the meaning-changing overrides (owner's order), with what to check.
PRIORITY_UNITS = {
    "uu27-2022": {
        "p26/a2": 'the PDF text layer lacks "menggunakan" in "dengan menggunakan cara tertentu"',
    },
}


class ReviewError(Exception):
    """A review line in the committed list is malformed."""


@dataclass(frozen=True)
class Review:
    reviewed_by: str
    verdict: str


def read_reviews(text: str) -> dict[tuple[str, str], Review]:
    """Completed review lines, keyed by (section number, unit id)."""
    out: dict[tuple[str, str], Review] = {}
    section, unit = "", None
    for line in text.splitlines():
        if m := _SECTION.match(line):
            section, unit = m.group(1), None
        elif m := _HEADING.match(line):
            unit = m.group(1)
        elif (m := _REVIEW.fullmatch(line.strip())) and unit is not None:
            who, verdict = m.groups()
            if (who == PENDING) != (verdict == PENDING):
                raise ReviewError(f"{unit}: set both reviewed_by and verdict, or neither")
            if verdict != PENDING and verdict not in VERDICTS:
                raise ReviewError(f"{unit}: verdict {verdict!r} not in {VERDICTS}")
            if who != PENDING:
                out[section, unit] = Review(who, verdict)
    return out


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " / ")


def _quote(text: str) -> str:
    return "> " + text.replace("\n", "\n> ")


def _review_line(reviews: dict[tuple[str, str], Review], section: str, unit_id: str) -> str:
    r = reviews.get((section, unit_id))
    return f"Review: reviewed_by: {r.reviewed_by} | verdict: {r.verdict}" if r else PENDING_LINE


def _override_table(overrides: list[Override]) -> list[str]:
    rows = [
        "| Unit | Komdigi text | Corrected | PDF page | Reason | Confirmed |",
        "|---|---|---|---|---|---|",
    ]
    return rows + [
        f"| `{o.unit_id}` | {_cell(o.find)} | {_cell(o.replace)} | {o.pdf_page} | "
        f"{_cell(o.reason)} | {o.confirmed_by or '-'} |"
        for o in overrides
    ]


def _progress(reviews: dict[tuple[str, str], Review], section: str, listed: list[str]) -> str:
    done = Counter(reviews[section, u].verdict for u in listed if (section, u) in reviews)
    detail = ", ".join(f"{v} {done[v]}" for v in VERDICTS if done[v])
    return f"{sum(done.values())} of {len(listed)}" + (f" ({detail})" if detail else "")


def _flagged(f: Finding, text: str, line: str) -> list[str]:
    out = [f"### `{f.unit_id}` {f.label}: coverage {f.coverage}, PDF page {f.pdf_page}", ""]
    out += [_quote(text), ""]
    if f.diffs:
        out += ["| Komdigi | PDF | Suspect | Context |", "|---|---|---|---|"]
        out += [
            f"| {_cell(d.html) or '-'} | {_cell(d.pdf) or '-'} | {d.suspect} | {_cell(d.context)} |"
            for d in f.diffs
        ]
        out.append("")
    return [*out, line, ""]


def review_markdown(
    entry: SourceEntry,
    result: TextResult,
    reviews: dict[tuple[str, str], Review] | None = None,
    *,
    snapshot: tuple[str, ...] | None = None,
    priority: dict[str, str] | None = None,
) -> str:
    sid = entry.source_id
    reviews = reviews or {}
    snapshot = SNAPSHOT_UNITS.get(sid, ()) if snapshot is None else snapshot
    priority = PRIORITY_UNITS.get(sid, {}) if priority is None else priority
    by_id = {u.unit_id: u for u in result.units}
    findings = {f.unit_id: f for f in result.findings}
    flagged = sorted((f for f in result.findings if f.needs_review), key=lambda f: f.coverage)
    flagged_ids = [f.unit_id for f in flagged]
    snapshot_ids = [f"{sid}/{s}" for s in snapshot]
    kinds = Counter(u.kind for u in result.units)
    total, unconfirmed = counts(result.overrides)
    meaning = [o for o in result.overrides if o.changes_meaning]
    other = [o for o in result.overrides if not o.changes_meaning]
    lines = [
        f"# Cross-check review: {sid}",
        "",
        "Generated by `make ingest` (`pdp_ingest.review`). Edit only the `Review:` lines and "
        f"`data/overrides/{sid}.yaml`; everything else is regenerated. Primary text: Komdigi "
        f"page, body sha256 `{entry.primary.body_sha256}`. Reference: salinan PDF "
        f"`{entry.reference.sha256}` (Penjelasan from PDF page {result.split_page}). Page numbers "
        "are 1-based PDF pages.",
        "",
        f"Units: {len(result.units)} ("
        + ", ".join(f"{k} {n}" for k, n in sorted(kinds.items()))
        + f"). Overrides: {total} total, {unconfirmed} unconfirmed. Flagged: {len(flagged)} "
        f"(coverage below {THRESHOLD}, or a word difference not attributed to PDF OCR).",
        "",
        f"Snapshot units reviewed: {_progress(reviews, SNAPSHOT_SECTION, snapshot_ids)}. "
        f"Flagged units reviewed: {_progress(reviews, FLAGGED_SECTION, flagged_ids)}.",
        "",
        "Review line values: `reviewed_by: <name> | verdict: <verdict>`, verdict one of "
        + ", ".join(f"`{v}`" for v in VERDICTS)
        + ". Overrides are confirmed by setting `confirmed_by` in the overrides file.",
        "",
        "## 1. Meaning-changing overrides and priority units",
        "",
        *_override_table(meaning),
        "",
    ]
    for suffix, check in priority.items():
        uid = f"{sid}/{suffix}"
        where = "flagged, review in §4" if uid in flagged_ids else "not flagged"
        lines.append(f"- `{uid}` {by_id[uid].label}: {check}; {where}")
    lines += ["", "## 2. Other overrides", "", *_override_table(other), "", "## 3. Snapshot units"]
    lines += ["", "Exact text pinned in `test_segment_uu27.py` (overrides applied).", ""]
    for uid in snapshot_ids:
        unit = by_id[uid]
        lines += [f"### `{uid}` {unit.label}, PDF page {findings[uid].pdf_page}", ""]
        lines += [_quote(unit.text), "", _review_line(reviews, SNAPSHOT_SECTION, uid), ""]
    lines += [
        "## 4. Flagged units",
        "",
        "Lowest coverage first. `suspect` is a heuristic for which side carries the error: `html` "
        "(Komdigi), `pdf` (OCR), `unclear`. A PDF-side gap usually means OCR dropped or merged "
        "words. A Komdigi error becomes an override.",
        "",
    ]
    for f in flagged:
        lines += _flagged(
            f, by_id[f.unit_id].text, _review_line(reviews, FLAGGED_SECTION, f.unit_id)
        )
    return "\n".join(lines).rstrip() + "\n"
