"""Committed reference review list, `data/review/<source_id>/refs.md` (M1.3, FR-PDP-03).

Unresolved references are logged, not dropped (FR-PDP-03): this list shows every mention that
does not become an internal `REFERENCES` edge, i.e. unresolved internal items, external
instruments, delegations (kept for PP 33/2026), and "Undang-Undang ini". Generated by
`make ingest`; a snapshot test fails when the committed copy is stale.
"""

from collections import Counter

from pdp_ingest.refs import Mention
from pdp_ingest.segment import Unit

RESOLUTIONS = ("EXACT", "UNRESOLVED", "SELF", "EXTERNAL_UNRESOLVED")
_WINDOW = 60


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " / ")


def _context(text: str, m: Mention) -> str:
    lo, hi = max(0, m.start - _WINDOW), min(len(text), m.end + _WINDOW)
    before = ("…" if lo else "") + text[lo : m.start]
    after = text[m.end : hi] + ("…" if hi < len(text) else "")
    return _cell(f"{before}**{m.text}**{after}")


def _table(header: str, rows: list[str]) -> list[str]:
    if not rows:
        return ["None.", ""]
    cols = header.count("|") - 1
    return [header, "|" + "---|" * cols, *rows, ""]


def refs_markdown(source_id: str, mentions: list[Mention], units: list[Unit]) -> str:
    text = {u.unit_id: u.text for u in units}
    kinds = Counter(m.kind for m in mentions)
    res = Counter(m.resolution for m in mentions)

    def ctx(m: Mention) -> str:
        return _context(text[m.unit_id], m)

    unresolved = [
        f"| `{m.unit_id}` | {_cell(m.text)} | {_cell('; '.join(m.unresolved))} | {ctx(m)} |"
        for m in mentions
        if m.resolution == "UNRESOLVED"
    ]
    external = [
        f"| `{m.unit_id}` | {_cell(m.instrument or '')} | {ctx(m)} |"
        for m in mentions
        if m.kind == "REFERENCE" and m.resolution == "EXTERNAL_UNRESOLVED"
    ]
    delegations = [
        f"| `{m.unit_id}` | {_cell(m.instrument or '')} | {ctx(m)} |"
        for m in mentions
        if m.kind == "DELEGATION"
    ]
    selfs = [f"| `{m.unit_id}` | {ctx(m)} |" for m in mentions if m.resolution == "SELF"]
    lines = [
        f"# Reference review: {source_id}",
        "",
        "Generated by `make ingest` (`pdp_ingest.refs_review`); do not edit. Mentions that do "
        "not become internal `REFERENCES` edges. Resolver accuracy is measured on the labeled "
        "sample in `evals/datasets/pdp-refs/` (06 §2.9).",
        "",
        f"Mentions: {len(mentions)} ("
        + ", ".join(f"{k} {n}" for k, n in sorted(kinds.items(), reverse=True))
        + f"). Internal targets: {sum(len(m.targets) for m in mentions)}.",
        "",
        "Resolution: " + ", ".join(f"{r} {res[r]}" for r in RESOLUTIONS) + ".",
        "",
        "## 1. Unresolved internal references",
        "",
        *_table("| Unit | Mention | Unresolved items | Context |", unresolved),
        "## 2. External references",
        "",
        *_table("| Unit | Instrument | Context |", external),
        "## 3. Delegations",
        "",
        "Kind DELEGATION; no graph edge yet (to be linked when PP 33/2026 is ingested).",
        "",
        *_table("| Unit | Instrument | Context |", delegations),
        "## 4. Self references",
        "",
        *_table("| Unit | Context |", selfs),
    ]
    return "\n".join(lines).rstrip() + "\n"
