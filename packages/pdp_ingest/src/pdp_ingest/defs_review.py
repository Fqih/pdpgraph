"""Committed definitions review list, `data/review/<source_id>/definitions.md` (M1.4).

Generated by `make ingest`, like `crosscheck.md`: the owner edits only the `Review:` lines,
which regeneration keeps (`review.read_reviews`). Sections:

1. every definition (term, aliases, node id, full text, usage counts); the owner checks term
   and text against the PDF: verdict `ok`, `term_wrong` or `text_wrong`;
2. the candidate DataCategory vocabulary from the classification Pasal; a code is `proposed`
   until its verdict is `confirmed` (`code_change` / `not_a_category` otherwise);
3. the term list exported for the index's protected terms (M1.6);
4. every informal (lowercase) match, which does not become a `USES_TERM` edge.
"""

from collections import Counter

from pdp_ingest.defs import DataCategory, Definition, TermUse, term_list
from pdp_ingest.review import PENDING_LINE, Review, ReviewError, read_reviews
from pdp_ingest.segment import Unit

DEFINITION_SECTION, CATEGORY_SECTION = "1", "2"
DEFINITION_VERDICTS = ("ok", "term_wrong", "text_wrong")
CATEGORY_VERDICTS = ("confirmed", "code_change", "not_a_category")
_SECTION_VERDICTS = {DEFINITION_SECTION: DEFINITION_VERDICTS, CATEGORY_SECTION: CATEGORY_VERDICTS}


def read_defs_reviews(text: str) -> dict[tuple[str, str], Review]:
    reviews = read_reviews(text, DEFINITION_VERDICTS + CATEGORY_VERDICTS)
    for (section, unit), r in reviews.items():
        allowed = _SECTION_VERDICTS.get(section, ())
        if r.verdict not in allowed:
            raise ReviewError(f"{unit}: verdict {r.verdict!r} not in {allowed}")
    return reviews


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " / ")


def _line(reviews: dict[tuple[str, str], Review], section: str, unit_id: str) -> str:
    r = reviews.get((section, unit_id))
    return f"Review: reviewed_by: {r.reviewed_by} | verdict: {r.verdict}" if r else PENDING_LINE


def _progress(reviews: dict[tuple[str, str], Review], section: str, listed: list[str]) -> str:
    done = Counter(reviews[section, u].verdict for u in listed if (section, u) in reviews)
    detail = ", ".join(f"{v} {done[v]}" for v in _SECTION_VERDICTS[section] if done[v])
    return f"{sum(done.values())} of {len(listed)}" + (f" ({detail})" if detail else "")


def defs_markdown(
    source_id: str,
    defs: list[Definition],
    uses: list[TermUse],
    categories: list[DataCategory],
    units: list[Unit],
    reviews: dict[tuple[str, str], Review] | None = None,
    pages: dict[str, int | None] | None = None,
) -> str:
    """`pages`: PDF page per unit id (cross-check), shown next to each definition."""
    reviews = reviews or {}
    pages = pages or {}
    text = {u.unit_id: u.text for u in units}
    term = {d.node_id: d.term for d in defs}
    kinds = Counter(u.kind for u in uses)
    occurrences = Counter(u.kind for u in uses for _ in u.spans)
    lines = [
        f"# Definitions review: {source_id}",
        "",
        "Generated by `make ingest` (`pdp_ingest.defs_review`). Edit only the `Review:` lines; "
        "everything else is regenerated.",
        "",
        f"Definitions: {len(defs)}. Defined uses (`USES_TERM` edges): {kinds['defined']} "
        f"unit-term links, {occurrences['defined']} occurrences. Informal uses (no edge): "
        f"{kinds['informal']} links, {occurrences['informal']} occurrences.",
        "",
        "Definitions reviewed: "
        + _progress(reviews, DEFINITION_SECTION, [d.unit_id for d in defs])
        + ". Categories reviewed: "
        + _progress(reviews, CATEGORY_SECTION, [c.unit_id for c in categories])
        + ".",
        "",
        "Verdicts: definitions "
        + ", ".join(f"`{v}`" for v in DEFINITION_VERDICTS)
        + "; categories "
        + ", ".join(f"`{v}`" for v in CATEGORY_VERDICTS)
        + ". A `code_change` marks a code to rename: say which code, it is changed in "
        "`pdp_ingest.defs` and the line set back to pending.",
        "",
        "## 1. Definitions",
        "",
    ]
    for d in defs:
        mine = [u for u in uses if u.node_id == d.node_id]
        defined = [u for u in mine if u.kind == "defined"]
        informal = sum(u.count for u in mine if u.kind == "informal")
        lines += [
            f"### `{d.unit_id}` {d.term}",
            "",
            f"Node: `{d.node_id}`; aliases: {', '.join(d.aliases) or '-'}; "
            f"PDF page {pages.get(d.unit_id) or '-'}",
            "",
            "> " + d.text.replace("\n", "\n> "),
            "",
            f"Defined uses: {sum(u.count for u in defined)} in {len(defined)} unit(s); "
            f"informal: {informal}",
            "",
            _line(reviews, DEFINITION_SECTION, d.unit_id),
            "",
        ]
    lines += [
        "## 2. Data categories",
        "",
        "Candidate `:DataCategory` codes derived from the classification Pasal (04 §3.1). A code "
        "is used downstream only once confirmed.",
        "",
    ]
    for c in categories:
        member = f" (member of {c.parent_code})" if c.parent_code else ""
        confirmed = reviews.get((CATEGORY_SECTION, c.unit_id))
        status = "confirmed" if confirmed and confirmed.verdict == "confirmed" else c.status
        lines += [
            f"### `{c.unit_id}` {c.code}{member}",
            "",
            f"Label: {c.label}. Status: {status}."
            + (" Open-ended (refers to other law)." if c.open else ""),
            "",
        ]
        if c.explanation:
            lines += ["> " + c.explanation.replace("\n", "\n> "), ""]
        lines += [_line(reviews, CATEGORY_SECTION, c.unit_id), ""]
    lines += [
        "## 3. Term list",
        "",
        "Terms and aliases for the index's protected terms (M1.6, `keyword_marker`); also in "
        f"`data/processed/{source_id}/terms.json`.",
        "",
        ", ".join(term_list(defs)),
        "",
        "## 4. Informal matches",
        "",
        "Case-insensitive matches with different capitalization. Not `USES_TERM` edges.",
        "",
    ]
    loose = [u for u in uses if u.kind == "informal"]
    if not loose:
        lines += ["None.", ""]
    else:
        lines += ["| Unit | Term | Matched |", "|---|---|---|"]
        lines += [
            f"| `{u.unit_id}` | {term[u.node_id]} | "
            + _cell("; ".join(text[u.unit_id][a:b] for a, b in u.spans))
            + " |"
            for u in loose
        ]
        lines.append("")
    return "\n".join(lines)
